package com.enviro.assessment.junior.thandeka.repository;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.springframework.boot.CommandLineRunner;
import org.springframework.context.annotation.Bean;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

@Repository
public class InvestmentRepository {
    private final JdbcTemplate db;

    public InvestmentRepository(JdbcTemplate db) { this.db = db; }

    @Bean
    CommandLineRunner sampleData() {
        return args -> {
            db.execute("CREATE TABLE IF NOT EXISTS investor (id BIGINT PRIMARY KEY, name VARCHAR(100), dob DATE)");
            db.execute("CREATE TABLE IF NOT EXISTS product (id BIGINT PRIMARY KEY, investor_id BIGINT, name VARCHAR(100), type VARCHAR(30), balance DECIMAL(15,2))");
            db.execute("CREATE TABLE IF NOT EXISTS withdrawal (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reference VARCHAR(40), investor_id BIGINT, product_name VARCHAR(100), amount DECIMAL(15,2), balance_after DECIMAL(15,2), created_at TIMESTAMP)");
            if (db.queryForObject("SELECT COUNT(*) FROM investor", Integer.class) == 0) {
                db.update("INSERT INTO investor VALUES (1, ?, ?)", "Alex Morgan", LocalDate.of(1954, 4, 12));
                db.update("INSERT INTO product VALUES (1, 1, 'Retirement Annuity', 'RETIREMENT', 185000.00)");
                db.update("INSERT INTO product VALUES (2, 1, 'Growth Investment', 'GENERAL', 62500.00)");
                db.update("INSERT INTO product VALUES (3, 1, 'Flexible Savings', 'GENERAL', 28000.00)");
            }
        };
    }

    public Map<String, Object> investor() {
        return db.queryForMap("SELECT name, dob FROM investor WHERE id = 1");
    }

    public List<Map<String, Object>> products() {
        return db.queryForList("SELECT id, name, type, balance FROM product WHERE investor_id = 1 ORDER BY id");
    }

    public List<Map<String, Object>> productForUpdate(long id) {
        return db.queryForList("SELECT id, name, type, balance FROM product WHERE id = ? AND investor_id = 1 FOR UPDATE", id);
    }

    public void saveWithdrawal(long productId, String name, BigDecimal amount,
                               BigDecimal remaining, String reference) {
        db.update("UPDATE product SET balance = ? WHERE id = ?", remaining, productId);
        db.update("INSERT INTO withdrawal (reference, investor_id, product_name, amount, balance_after, created_at) VALUES (?, 1, ?, ?, ?, ?)",
                reference, name, amount, remaining, LocalDateTime.now());
    }

    public List<Map<String, Object>> history(LocalDate from, LocalDate to) {
        String sql = "SELECT reference, product_name, amount, balance_after, created_at FROM withdrawal WHERE investor_id = 1";
        List<Object> parameters = new ArrayList<>();
        if (from != null) { sql += " AND created_at >= ?"; parameters.add(from.atStartOfDay()); }
        if (to != null) { sql += " AND created_at < ?"; parameters.add(to.plusDays(1).atStartOfDay()); }
        return db.queryForList(sql + " ORDER BY created_at DESC, id DESC", parameters.toArray());
    }
}
